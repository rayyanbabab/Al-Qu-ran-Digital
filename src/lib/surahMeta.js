/**
 * Mengambil nama Indonesia resmi untuk nomor surah
 */
export const getSurahNameId = (surahNumber) => {
  return SURAH_NAMES_ID[Number(surahNumber)] || null;
};

/**
 * Normalisasi teks pencarian untuk toleransi transliterasi Arab-Indonesia-Inggris
 */
export const normalizeSearchText = (str) => {
  if (!str) return '';
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // hilangkan diakritik
    .replace(/[^a-z0-9]/g, '') // hilangkan tanda baca, spasi, tanda petik, strip
    .replace(/ah$/, 'a') // ta marbutah: fatihah -> fatiha
    .replace(/sh/g, 'sy') // ash-shams -> asy-syams
    .replace(/th/g, 'ts') // kauthar -> kautsar
    .replace(/dh/g, 'd') // dhuha -> duha
    .replace(/dz/g, 'z') // zalzalah -> dzalzalah
    .replace(/aa+/g, 'a')
    .replace(/ee+/g, 'i')
    .replace(/oo+/g, 'u');
};

/**
 * Cek kecocokan surah dengan kata kunci pencarian
 */
export const isSurahMatch = (surah, query) => {
  if (!query || !query.trim()) return true;

  const rawQuery = query.trim().toLowerCase();
  const normQuery = normalizeSearchText(query);
  const surahNum = Number(surah.number_of_surah);

  // 1. Cek kecocokan nomor surah (misal: "1", "01", "surah 1", "surat 36", "no. 114")
  const numMatch = rawQuery.match(/^(?:surah|surat|no\.?|ke-?)?\s*(\d+)$/i);
  if (numMatch && parseInt(numMatch[1], 10) === surahNum) {
    return true;
  }
  if (surahNum.toString() === rawQuery) {
    return true;
  }

  // 2. Kumpulkan semua representasi teks surah
  const nameId = getSurahNameId(surahNum);
  const aliases = SURAH_ALIASES[surahNum] || [];
  const textPool = [
    surah.name,
    nameId,
    surah.name_translations?.id,
    surah.name_translations?.en,
    surah.name_translations?.ar,
    ...aliases,
  ].filter(Boolean);

  // 3. Cek pencarian langsung (substring check)
  for (const text of textPool) {
    if (text.toLowerCase().includes(rawQuery)) {
      return true;
    }
  }

  // 4. Cek pencarian ternormalisasi (toleran strip, spasi, tanda petik, ta marbutah, dll)
  if (normQuery) {
    for (const text of textPool) {
      if (normalizeSearchText(text).includes(normQuery)) {
        return true;
      }
    }
  }

  return false;
};
